import { useState } from 'react';
import { useOverlayDismiss } from '../../hooks/useOverlayDismiss';
import {
  GitHubApiError,
  createBranch,
  createPullRequest,
  getBranchSha,
  getFileContent,
  putFileContent,
  setIssueLabelsAndAssignees,
} from '../../lib/github';
import type { LibraryEntry } from '../../types/library';

const OWNER = 'jongeuni';
const REPO = 'github-readme-canvas';
const DATA_DIR = 'src/data/community-components';
const PR_LABELS = ['new component'];
const PR_ASSIGNEES = ['jongeuni'];

function slugify(name: string): string {
  return (
    name
      .trim()
      .toLowerCase()
      .replace(/[^a-z0-9]+/g, '-')
      .replace(/(^-|-$)/g, '') || 'component'
  );
}

type Result = { kind: 'success'; url: string; number: number } | { kind: 'error'; message: string };

export function SubmitComponentPrModal({
  open,
  token,
  entry,
  onCancel,
}: {
  open: boolean;
  token: string | null;
  entry: LibraryEntry | null;
  onCancel: () => void;
}) {
  const [busy, setBusy] = useState(false);
  const [result, setResult] = useState<Result | null>(null);
  const overlayDismiss = useOverlayDismiss(onCancel);

  const submit = async () => {
    if (!token || !entry) return;
    setBusy(true);
    setResult(null);
    try {
      const baseSha = await getBranchSha(token, OWNER, REPO, 'main');
      const branch = `add-component-${slugify(entry.name)}-${Date.now()}`;
      await createBranch(token, OWNER, REPO, branch, baseSha);

      // One file per component (filename = its id) — find a free id/path
      // instead of every contributor's PR racing to edit one shared array.
      let id = entry.id;
      let n = 2;
      while (await getFileContent(token, OWNER, REPO, `${DATA_DIR}/${id}.json`, branch)) {
        id = `${entry.id}-${n}`;
        n += 1;
      }

      const content = JSON.stringify({ ...entry, id }, null, 2) + '\n';
      await putFileContent(token, OWNER, REPO, `${DATA_DIR}/${id}.json`, {
        message: `Add component: ${entry.name}`,
        content,
        branch,
      });

      const pr = await createPullRequest(token, OWNER, REPO, {
        title: `Add component: ${entry.name}`,
        head: branch,
        base: 'main',
        body: `Adds "${entry.name}" as a new component in the library.\n\n- Category: ${entry.category}\n- Description: ${entry.description}\n\nGenerated by GitHub Readme Canvas's "Add Component" flow.`,
      });
      // Best-effort — a missing label/invalid assignee shouldn't turn an
      // otherwise-successful PR into an error.
      try {
        await setIssueLabelsAndAssignees(token, OWNER, REPO, pr.number, { labels: PR_LABELS, assignees: PR_ASSIGNEES });
      } catch {
        // ignore
      }
      setResult({ kind: 'success', url: pr.htmlUrl, number: pr.number });
    } catch (e) {
      setResult({ kind: 'error', message: e instanceof GitHubApiError ? e.message : 'Submission failed.' });
    } finally {
      setBusy(false);
    }
  };

  if (!open || !entry) return <div className="modal-overlay" />;

  return (
    <div className="modal-overlay open" {...overlayDismiss}>
      <div className="modal-card">
        <h4>Submit PR to GitHub</h4>
        <p className="field-hint" style={{ marginTop: 0 }}>
          {'Proposes "'}
          {entry.name}
          {'" as a new component in the github-readme-canvas project. Creates a new branch, adds it as a new file under '}
          <code>src/data/community-components/</code>
          {', and opens a PR automatically.'}
        </p>
        {result?.kind === 'success' && (
          <div className="banner success" style={{ borderRadius: 8, marginBottom: 12 }}>
            PR opened · #{result.number}
            <a href={result.url} target="_blank" rel="noreferrer">
              View PR ↗
            </a>
          </div>
        )}
        {result?.kind === 'error' && <div className="field-error">{result.message}</div>}
        <div className="modal-actions">
          <button type="button" className="btn btn-ghost btn-sm" onClick={onCancel}>
            Close
          </button>
          {result?.kind !== 'success' && (
            <button type="button" className="btn btn-primary btn-sm" onClick={submit} disabled={busy}>
              {busy ? 'Submitting...' : 'Submit PR'}
            </button>
          )}
        </div>
      </div>
    </div>
  );
}
